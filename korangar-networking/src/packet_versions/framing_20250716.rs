#[derive(Debug, PartialEq, Eq)]
pub enum FrameError {
    UnknownOpcode(u16),
    InvalidLength,
}
/// Return a complete frame length, a cut-off indication, or malformed input.
pub fn frame_length(bytes: &[u8]) -> Result<Option<usize>, FrameError> {
    if bytes.len() < 2 {
        return Ok(None);
    }
    let opcode = u16::from_le_bytes([bytes[0], bytes[1]]);
    let length = packet_length(opcode).ok_or(FrameError::UnknownOpcode(opcode))?;
    let size = if length == -1 {
        if bytes.len() < 4 {
            return Ok(None);
        }
        let size = u16::from_le_bytes([bytes[2], bytes[3]]) as usize;
        if size < 4 {
            return Err(FrameError::InvalidLength);
        }
        size
    } else {
        length as usize
    };
    Ok((bytes.len() >= size).then_some(size))
}
